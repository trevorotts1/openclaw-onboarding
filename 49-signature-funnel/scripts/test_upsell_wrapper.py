class FailClosedTests(unittest.TestCase):
    def assert_fails_naming(self, proc, *names):
        self.assertNotEqual(proc.returncode, 0,
                            f"expected fail-closed, got success: {proc.stdout}")
        for name in names:
            self.assertIn(name, proc.stderr)

    def test_missing_offer_names_offer(self):
        def drop_u1(record):
            record["offers"] = [o for o in record["offers"]
                                if o["slot"] != "upsell_1"]
        wd, *_ = make_workdir(drop_u1)
        self.addCleanup(shutil.rmtree, wd, True)
        proc = run_wrapper(
            wd, "upsell_1",
            copy_path=S80_FIX / "copy-upsell1-public.valid.json",
            journey_path=ADAPT_FIX / "journey-main-only.testonly.json",
            enrichment=FIXTURES / "enrichment-upsell_1.json")
        self.assert_fails_naming(proc, "offer")

    def test_unknown_price_names_disclosure_amount(self):
        def unknown_u1_price(record):
            for offer in record["offers"]:
                if offer["slot"] == "upsell_1":
                    offer["prices"][0]["amount_minor"] = None
                    offer["prices"][0]["approval_status"] = "unknown"
        wd, *_ = make_workdir(unknown_u1_price)
        self.addCleanup(shutil.rmtree, wd, True)
        proc = run_wrapper(
            wd, "upsell_1",
            copy_path=S80_FIX / "copy-upsell1-public.valid.json",
            journey_path=ADAPT_FIX / "journey-main-only.testonly.json",
            enrichment=FIXTURES / "enrichment-upsell_1.json")
        self.assert_fails_naming(proc, "disclosure.amount_minor")

    def test_recurring_without_terms_names_recurring_terms(self):
        wd, *_ = make_workdir(Upsell2EndToEndTests._recurring_u2)
        self.addCleanup(shutil.rmtree, wd, True)
        proc = run_wrapper(
            wd, "upsell_2",
            copy_path=S80_FIX / "copy-upsell2-public.valid.json",
            journey_path=ADAPT_FIX / "journey-upsell2-from-downsell1.testonly.json",
            enrichment=FIXTURES / "enrichment-upsell_2-onetime.json")
        self.assert_fails_naming(proc, "disclosure.recurring_terms")

    def test_no_landing_copy_ref_source_names_it(self):
        wd, *_ = make_workdir()
        self.addCleanup(shutil.rmtree, wd, True)
        empty_sidecar = wd / "empty-sidecar.json"
        empty_sidecar.write_text("{}\n", encoding="utf-8")
        proc = run_wrapper(
            wd, "upsell_1",
            copy_path=S80_FIX / "copy-upsell1-public.valid.json",
            journey_path=ADAPT_FIX / "journey-main-only.testonly.json",
            enrichment=empty_sidecar)
        self.assert_fails_naming(proc, "source_landing_copy_ref")

    def test_u2_without_qualifying_journey_names_blocks(self):
        wd, *_ = make_workdir()
        self.addCleanup(shutil.rmtree, wd, True)
        proc = run_wrapper(
            wd, "upsell_2",
            copy_path=S80_FIX / "copy-upsell2-public.valid.json",
            journey_path=ADAPT_FIX / "journey-main-only.testonly.json",
            enrichment=FIXTURES / "enrichment-upsell_2-onetime.json")
        self.assert_fails_naming(proc, "entry_context",
                                 "eligibility.qualifying_purchase")

    def test_tampered_route_graph_names_routes(self):
        wd, *_ = make_workdir()
        self.addCleanup(shutil.rmtree, wd, True)
        graph_path = wd / "route-graph.json"
        graph_path.write_bytes(graph_path.read_bytes() + b" ")
        proc = run_wrapper(
            wd, "upsell_1",
            copy_path=S80_FIX / "copy-upsell1-public.valid.json",
            journey_path=ADAPT_FIX / "journey-main-only.testonly.json",
            enrichment=FIXTURES / "enrichment-upsell_1.json")
        self.assert_fails_naming(proc, "routes")

    def test_request_with_unknown_field_is_refused(self):
        # DEFECT 1 cure: the wrapper consumes page-request 1.0-shaped
        # requests only. A 1.1 field (prompt_policy_id) or any other
        # unknown key fails closed naming the key, before produce.py
        # runs: no result written and no enriched request staged.
        for bad_key in ("prompt_policy_id", "totally_unknown_field"):
            wd, *_ = make_workdir()
            self.addCleanup(shutil.rmtree, wd, True)
            request_path = wd / "request-upsell_1.json"
            request = load(request_path)
            request[bad_key] = "TEST-POLICY" if bad_key == "prompt_policy_id" \
                else "bogus"
            request_path.write_text(json.dumps(request, indent=2) + "\n",
                                    encoding="utf-8")
            proc = run_wrapper(
                wd, "upsell_1",
                copy_path=S80_FIX / "copy-upsell1-public.valid.json",
                journey_path=ADAPT_FIX / "journey-main-only.testonly.json",
                enrichment=FIXTURES / "enrichment-upsell_1.json")
            self.assertEqual(proc.returncode, 2, proc.stdout + proc.stderr)
            self.assertIn(bad_key, proc.stderr)
            self.assertFalse((wd / "result-upsell_1.json").exists(),
                             "no result may be written for a refused request")
            self.assertFalse((wd / "upsell-request-upsell_1.json").exists(),
                             "refusal must happen in enrich(), before the "
                             "enriched request (and produce.py) is reached")

    def test_result_with_wrong_echo_is_refused_not_repaired(self):
        request = {"request_id": "r1", "input_hash": "REAL", "page_id": "P",
                   "launch_id": "L", "revision": 1, "tenant_id": "T",
                   "location_id": "LOC", "test_only": True}
        bundle = {"result": {f: None for f in wrapper.RESULT_FIELDS}}
        bundle["result"].update({"input_hash": "FORGED", "request_id": "r1",
                                 "page_id": "P", "launch_id": "L", "revision": 1,
                                 "tenant_id": "T", "location_id": "LOC",
                                 "test_only": True})
        with self.assertRaises(wrapper.EnrichmentError) as ctx:
            wrapper.project_result(bundle, request)
        self.assertIn("input_hash", str(ctx.exception))


class ConfigFragmentTests(unittest.TestCase):
    def test_fragment_shape_and_separate_invocations(self):
        # Assembly re-point (S49-08 assembly, disclosed in the assembly
        # readiness): the staged adapters-fragment.json was merged into
        # the shipped 49-signature-funnel/launch-adapters.example.json,
        # so this test asserts on the shipped merged config. Every
        # per-entry assertion below is the staged one; the fragment
        # whole-object set equality is replaced by the exact five-role
        # presence assertion plus the two honest absences (checkout
        # closed by design per CR-S49-003; downsell_1 has no consumer
        # until Skill 81 lands on main).
        # Downsell assembly re-point (S49 downsell wrapper assembly,
        # disclosed in its assembly report): Skill 81 has since landed
        # on main (PR #2229, train #2235) and the downsell_1 consumer
        # ships in this tree, so the merged config now wires six
        # roles; the presence assertion below is the exact six-role
        # set and checkout is the one remaining honest absence. Every
        # per-entry assertion is unchanged.
        config = load(CONFIG)
        adapters = config["adapters"]
        self.assertEqual(set(adapters),
                         {"downsell_1", "landing", "product_selection",
                          "upsell_1", "upsell_2", "thank_you"})
        self.assertNotIn("checkout", adapters)
        commands = {}
        for role in ("upsell_1", "upsell_2"):
            spec = adapters[role]
            cmd = spec["command"]
            commands[role] = cmd
            self.assertIn("{request}", cmd)
            self.assertIn("{result}", cmd)
            self.assertEqual(cmd[cmd.index("--slot") + 1], role)
            self.assertTrue(any("upsell_wrapper.py" in part for part in cmd))
            self.assertTrue(any("produce.py" in part for part in cmd))
        self.assertNotEqual(commands["upsell_1"], commands["upsell_2"])


