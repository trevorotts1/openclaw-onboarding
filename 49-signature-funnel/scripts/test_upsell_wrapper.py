# page_role is added by the wrapper from the S49 request (Skill 80's own result does not carry it),
# so the parity comparison with Skill 80's stored result ignores it like the other S49-side fields.
IDENTITY_FIELDS = ("request_id", "input_hash", "page_id", "page_role")


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def strip_identity(result):
    return {k: v for k, v in result.items() if k not in IDENTITY_FIELDS}


def project_expected(bundle_result):
    """Project a stored Skill 80 bundle result to the 17 S49 fields,
    exactly as the wrapper projects: the parity claim is that the
    wrapper's projection equals Skill 80's own values, field for field."""
    return {f: bundle_result[f] for f in wrapper.RESULT_FIELDS}


def make_workdir(record_mutator=None):
    """A dispatch-shaped work dir: launch.json, route-graph.json (the
    compiler's exact bytes), request-<role>.json for both upsell roles,
    built with S49's landed compiler + dispatch code."""
    wd = Path(tempfile.mkdtemp(prefix="s49-08-upsell-"))
    record = load(FIXTURES / "test-launch-record.json")
    if record_mutator:
        record_mutator(record)
    graph = clr.compile_route(record)
    record["route_graph_hash"] = clr.graph_hash(graph)
    (wd / "launch.json").write_text(json.dumps(record, indent=2) + "\n",
                                    encoding="utf-8")
    (wd / "route-graph.json").write_bytes(clr.serialize_graph(graph))
    requests = dispatch.build_requests(record, graph, copy_profile="standard",
                                       allowed_write_target="local_only")
    by_role = {}
    for req in requests:
        (wd / f"request-{req['page_role']}.json").write_text(
            json.dumps(req, indent=2) + "\n", encoding="utf-8")
        by_role[req["page_role"]] = req
    return wd, record, graph, by_role


U1_COPY = S80_FIX / "copy-upsell1-public.valid.json"


def run_wrapper(wd, slot, *, copy_path, journey_path, enrichment=None,
                artifact_path=None, u1_copy=U1_COPY, extra=()):
    cmd = [sys.executable, str(WRAPPER), "--slot", slot,
           "--request", str(wd / f"request-{slot}.json"),
           "--result", str(wd / f"result-{slot}.json"),
           "--launch", str(wd / "launch.json"),
           "--copy", str(copy_path), "--journey", str(journey_path),
           "--produce", str(PRODUCE)]
    if enrichment is not None:
        cmd += ["--enrichment", str(enrichment)]
    if artifact_path is not None:
        cmd += ["--copy-artifact-path", artifact_path]
    if slot == "upsell_2" and u1_copy is not None:
        cmd += ["--u1-copy", str(u1_copy)]
    return subprocess.run(cmd + list(extra), capture_output=True, text=True)


def assert_receipt_valid(testcase, wd, slot, request):
    result = load(wd / f"result-{slot}.json")
    testcase.assertEqual(set(result), set(wrapper.RESULT_FIELDS) | {"page_role"},
                         "projected result must carry exactly the 17 fields plus page_role")
    testcase.assertEqual(result["page_role"], request["page_role"],
                         "the canonical page-result schema requires page_role, echoed from the request")
    testcase.assertEqual(receipts.validate_result(result, request), [],
                         "collect_launch_receipts must accept the result "
                         "with an exact request echo")
    return result


