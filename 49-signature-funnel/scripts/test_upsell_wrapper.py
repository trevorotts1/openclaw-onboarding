        jsonschema.validate(result, load(PACKET_SCHEMAS / "page-result.schema.json"))
        enriched = load(wd / "upsell-request-upsell_1.json")
        jsonschema.validate(
            enriched, load(SKILL80 / "components/80-signature-upsell"
                           / "schemas" / "upsell-request.schema.json"))
        self.assertEqual(enriched["approval_hash"], vlp.plan_document_hash(record))
        self.assertIsNone(enriched["entry_context"])
        bundle = load(wd / "bundle-upsell_1.json")
