#!/usr/bin/env bash
# ==============================================================================
# signature-funnel-entry.sh — the CANONICAL, fail-closed front door for Skill 49
# (Signature Funnel). NOTHING may generate copy/prompts, call Kie, touch GHL, or
# mint a certificate except THROUGH this shell. It performs, in order and all
# fail-closed:
#
#   1. DEPS        — python3 present (else abort).
#   2. VERSION     : skill-version.txt is present, vMAJOR.MINOR.PATCH on the pinned
#                    major (2), and equals the SKILL.md frontmatter version.
#   3. HASH-PIN    — recompute the sha256 of every file the dispatch/launch path
#                    executes or reads for decisions (scripts/front_door.py generates
#                    the list: provers, wrappers, page types, the 83 launcher tree, the
#                    71 page-build tree, the shared contract validator) and compare to
#                    SF-PROVER-PIN.sha256.
#                    The pin is CI-minted only. Skill 83's launcher runs the same gate.
#   4. BYPASS-SCAN — refuse a run (or a skill tree) whose files hand-roll GHL REST calls or
#                    mail/senders instead of delegating to Skill 6 / Skill 66 + Skill 74.
#                    Skill 74 (74-kie-live-adapter) is the ONE approved KIE path: its own
#                    result files under <RUN_DIR>/receipts/kie74/ are allow-listed (each is
#                    re-checked by scripts/kie74_receipt.py --check); anything else that
#                    names the createTask route or a KIE client script is a bypass.
#                    (Authorship + build MUST go through the delegated adapters.)
#   5. MODEL-TIER  — verify the HARNESS-minted, operator-key-signed authoring-model
#                    receipt (minting it from SF_ROUTING_RECORD when the harness
#                    supplied one). An env-reported receipt is refused.
#   6. ORCHESTRATE — run_signature_funnel.py (the no-skip state machine). It
#                    authorizes on the OPERATOR KEY only, so a caller-supplied
#                    --nonce / --nonce-file / SF_RUN_NONCE is refused with
#                    AF-FUN-FRONT-DOOR; this shell mints and forwards none. It emits
#                    the signed PROCESS-CERTIFICATE only on all-phases-pass.
#
#   Bare invocation (no arguments) prints this usage and exits 0; every real mode
#   still runs every gate above, fail-closed.
#
# Usage:
#   bash signature-funnel-entry.sh --run-dir <RUN_DIR>
#   bash signature-funnel-entry.sh --mode signature_launch --run-dir <RUN_DIR>
#   bash signature-funnel-entry.sh --self-test
#   bash signature-funnel-entry.sh --check-version   (version gate only)
#   bash signature-funnel-entry.sh --scan-only --run-dir <RUN_DIR>   (deps + bypass-scan only)
# Exit: 0 = certified / self-test green; nonzero = a fail-closed guard tripped.
#
# MODES (additive; spec 06): the default mode is legacy_signature_funnel — the
# pipeline below, byte-for-byte the historical behavior. `--mode
# signature_launch` dispatches an APPROVED launch plan to the specialist page
# skills via scripts/dispatch_launch.py. New launch requests must name their
# mode explicitly: a run dir carrying a signature_launch launch-request.json
# is REFUSED by the legacy path, never silently run through the old pipeline.
#
# EXECUTION vs EMISSION: the approved consumer-adapter configuration travels in
# launch-request.json ("adapters": {<page_role or extra-page key>: {"command": [...], "timeout_s": n}}),
# and the dispatcher executes through it. This shell forwards the run dir only —
# never a --simulate-executor flag — so a launch through the canonical entry can
# execute the owning skills' real entrypoints but can never fabricate results.
# ==============================================================================
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
SCRIPTS_DIR="$SKILL_DIR/scripts"
PIN_FILE="$SCRIPTS_DIR/SF-PROVER-PIN.sha256"
PY="${PYTHON:-python3}"
# Current contract: skill-version.txt is "vMAJOR.MINOR.PATCH" (see scripts/qc-assert-skill-version-newline.sh)
# and this skill is on major 2 (SKILL.md frontmatter version: v2.x). Bump only on a breaking 3.0.0 release.
EXPECTED_MAJOR="2"

# The pin list, the hash-pin gate and the bypass scan live in scripts/front_door.py - the ONE front door
# Skill 83's launcher also calls - so this shell and the launcher cannot drift apart. The pin is minted only
# by CI (.github/workflows/sf-prover-pin-authority.yml); --write-pin below needs a signed pin_rotation record.
FRONT_DOOR="$SCRIPTS_DIR/front_door.py"

# The enforcement-core FLOOR, relative to this skill dir. The pin itself is generated by
# scripts/front_door.py (every decision file of the dispatch/launch path, 49 + 83 + shared contract) and is a
# superset of this list; step_hashpin refuses if the generated list ever stops covering one of these.
PINNED_FILES=(
  "scripts/prove_sf_intake.py"
  "scripts/prove_sf_copy.py"
  "scripts/prove_sf_prompt_floor.py"
  "scripts/prove_sf_graph.py"
  "scripts/prove_sf_build.py"
  "scripts/prove_sf_no_pitch.py"
  "scripts/prove_sf_cert.py"
  "scripts/gate_integrity_check.py"
  "structure/funnel_structure.json"
  "run_signature_funnel.py"
  # A10 / T0-09, T0-10 — the delegated-phase receipt contract is enforcement core:
  # the P-IMAGES/-MEDIA/-DOCS/-DELIVER/-HANDOFF seams call require()/validate_if_present(),
  # so an unpinned copy could be swapped for a permissive one without tripping the pin.
  "scripts/delegation_receipt.py"
  # Skill 74 evidence writer + allow-list check used by the bypass scan below.
  "scripts/kie74_receipt.py"
  # The launch dispatch chain: these decide which pages, routes and prompts are
  # built and dispatched, so a swapped copy changes behaviour without touching
  # any prover above.
  "scripts/dispatch_launch.py"
  "scripts/compile_launch_route.py"
  "scripts/page_set.py"
  "scripts/page_swarm.py"
  "scripts/validate_launch_plan.py"
  "scripts/agnes_dispatch.py"
  "scripts/agnes_gates.py"
  "scripts/agnes_orchestrator.py"
  "scripts/agnes_response.py"
)

die() { printf 'ABORT [%s]: %s\n' "$1" "$2" >&2; exit 1; }

step_deps() {
  command -v "$PY" >/dev/null 2>&1 || die "DEPS" "python3 not found on PATH"
}

step_version() {
  local vf="$SKILL_DIR/skill-version.txt"
  [ -s "$vf" ] || die "VERSION" "skill-version.txt missing/empty"
  local v; v="$(tr -d '[:space:]' < "$vf")"
  # Accept the shipped form vMAJOR.MINOR.PATCH (a bare MAJOR.MINOR.PATCH is tolerated too).
  [[ "$v" =~ ^v?${EXPECTED_MAJOR}\.[0-9]+\.[0-9]+$ ]] \
    || die "VERSION" "skill-version.txt is '$v', expected major $EXPECTED_MAJOR.x.y (vMAJOR.MINOR.PATCH)"
  # Lockstep: SKILL.md frontmatter version must equal skill-version.txt (checked whenever SKILL.md ships beside it).
  [ -f "$SKILL_DIR/SKILL.md" ] || return 0
  local fm; fm="$(awk '$0=="---"{f++; if(f>=2) exit; next} f==1 && /^version:/{sub(/^version:[ \t]*/,""); print; exit}' "$SKILL_DIR/SKILL.md" | tr -d '[:space:]"'"'"'')"
  [ -n "$fm" ] || die "VERSION" "SKILL.md has no top-level frontmatter version: field"
  [ "$fm" = "$v" ] || die "VERSION" "SKILL.md frontmatter version ($fm) != skill-version.txt ($v) - drift"
}

step_hashpin() {
  "$PY" "$FRONT_DOOR" hashpin --must-cover "${PINNED_FILES[@]}" >/dev/null || exit 1
}

step_bypass_scan() {
  local rd="$1"
  # Scans the skill tree (strings + AST network check) and, when the run dir exists, the run dir.
  "$PY" "$FRONT_DOOR" bypass-scan --run-dir "$rd" >/dev/null || exit 1
}

# FIX-XC-09e / A6 — the CLIENT's own execution-tier authoring model (role=content) must be
# recorded in routing/model-content-receipt.json and gated (fail-closed) via prove_sf_cert
# --model-receipt. prove_sf_cert accepts ONLY a harness-minted, operator-key-signed receipt
# (resolved_from=harness-routing-record + harness_sig): a receipt this shell wrote from
# SF_CONTENT_* environment values is env-reported and is refused as AF-FUN-MODEL-TIER.
# So the shell mints from the harness routing record when one is supplied, and otherwise
# verifies the receipt the harness already wrote. It never invents one.
step_model_receipt() {
  local rd="$1"
  if [ -n "${SF_ROUTING_RECORD:-}" ]; then
    "$PY" "$SCRIPTS_DIR/prove_sf_cert.py" --mint-model-receipt "$SF_ROUTING_RECORD" --run-dir "$rd" \
      || die "MODEL-TIER" "the harness routing record could not be minted (the operator key is required)"
  fi
  "$PY" "$SCRIPTS_DIR/prove_sf_cert.py" --model-receipt "$rd/routing/model-content-receipt.json" \
    || die "MODEL-TIER" "content-authoring model receipt failed the execution-tier gate — the HARNESS must mint it from its routing record (prove_sf_cert.py --mint-model-receipt); an env-reported model is refused"
}

# Launch mode: same front-door integrity guards (deps / version / hash-pin /
# bypass-scan), then the launch dispatcher — which re-checks the plan
# approval gate itself before emitting or executing anything. The legacy
# model-tier receipt and certificate nonce belong to the legacy pipeline and
# are not part of launch mode.
run_launch_pipeline() {
  local rd="$1"
  [ -n "$rd" ] || die "USAGE" "--mode signature_launch needs --run-dir"
  rd="$(cd "$rd" 2>/dev/null && pwd || true)"
  [ -n "$rd" ] && [ -d "$rd" ] || die "USAGE" "run-dir does not exist"
  [ -f "$rd/launch.json" ] || die "MODE" "launch run dir has no launch.json"
  [ -f "$rd/approval.json" ] || die "MODE" "launch run dir has no approval.json"
  [ -f "$rd/launch-request.json" ] || die "MODE" "launch run dir has no launch-request.json (mode + identities)"
  step_deps
  step_version
  step_hashpin
  step_bypass_scan "$rd"
  echo "== signature-funnel-entry :: launch mode front door cleared (deps/version/hash-pin/bypass) =="
  # The approved adapters ride in launch-request.json (read by the dispatcher);
  # --simulate-executor is deliberately NOT forwardable from this guarded door.
  "$PY" "$SCRIPTS_DIR/dispatch_launch.py" --run-dir "$rd"
}

run_pipeline() {
  local rd="$1"
  [ -n "$rd" ] || die "USAGE" "--run-dir is required"
  rd="$(cd "$rd" 2>/dev/null && pwd || true)"
  [ -n "$rd" ] && [ -d "$rd" ] || die "USAGE" "run-dir does not exist"
  # Explicit mode required for new launch requests: never run a launch-mode
  # run dir through the legacy pipeline by accident.
  if [ -f "$rd/launch-request.json" ] && grep -q '"signature_launch"' "$rd/launch-request.json" 2>/dev/null; then
    die "MODE" "this run dir declares mode signature_launch; re-run with --mode signature_launch"
  fi
  step_deps
  step_version
  step_hashpin
  step_bypass_scan "$rd"
  step_model_receipt "$rd"
  echo "== signature-funnel-entry :: front door cleared (deps/version/hash-pin/bypass/model-tier) =="
  # A6: the runner refuses a caller-supplied nonce (AF-FUN-FRONT-DOOR). The operator key is
  # the authorization, so this shell mints none and forwards none.
  env -u SF_RUN_NONCE "$PY" "$SKILL_DIR/run_signature_funnel.py" --run-dir "$rd"
}

self_test() {
  echo "== signature-funnel-entry :: --self-test =="
  step_deps
  step_version
  if [ -f "$PIN_FILE" ]; then step_hashpin; echo "  [PASS] hash-pin verified"; else echo "  [WARN] no pin file yet (mint with --write-pin)"; fi
  local fails=0
  for p in prove_sf_intake prove_sf_copy prove_sf_prompt_floor prove_sf_graph prove_sf_build prove_sf_no_pitch prove_sf_cert; do
    if "$PY" "$SCRIPTS_DIR/$p.py" --self-test >/tmp/sf_$p.log 2>&1; then
      echo "  [PASS] $p.py --self-test"
    else
      echo "  [FAIL] $p.py --self-test"; sed 's/^/         /' "/tmp/sf_$p.log"; fails=$((fails+1))
    fi
  done
  if "$PY" "$SCRIPTS_DIR/kie74_receipt.py" --self-test >/tmp/sf_kie74.log 2>&1 \
     && "$PY" "$SCRIPTS_DIR/test_sf_bypass_scan.py" >>/tmp/sf_kie74.log 2>&1; then
    echo "  [PASS] kie74_receipt.py --self-test + test_sf_bypass_scan.py (Skill 74 is the allow-listed KIE path)"
  else
    echo "  [FAIL] kie74_receipt / bypass-scan allow-list"; sed 's/^/         /' /tmp/sf_kie74.log; fails=$((fails+1))
  fi
  if "$PY" "$SKILL_DIR/run_signature_funnel.py" --self-test >/tmp/sf_orch.log 2>&1; then
    echo "  [PASS] run_signature_funnel.py --self-test"
  else
    echo "  [FAIL] run_signature_funnel.py --self-test"; sed 's/^/         /' /tmp/sf_orch.log; fails=$((fails+1))
  fi
  # FIX-XC-05a — gate-integrity harness: (re)emit the negative-test coverage, then
  # prove DECLARED == ENFORCED == TESTED for every python-enforced autofail.
  if "$PY" "$SCRIPTS_DIR/test_sf_gate_coverage.py" >/tmp/sf_cov.log 2>&1 \
     && "$PY" "$SCRIPTS_DIR/gate_integrity_check.py" >/tmp/sf_gic.log 2>&1; then
    echo "  [PASS] gate_integrity_check.py (declared==enforced==tested)"
  else
    echo "  [FAIL] gate_integrity_check.py"; sed 's/^/         /' /tmp/sf_cov.log /tmp/sf_gic.log; fails=$((fails+1))
  fi
  # Signature Launch mode (additive): the launch toolchain self-tests ride the
  # same front-door self-test so a broken launch script fails the door loudly.
  for p in compile_launch_route validate_launch_plan launch_intake dispatch_launch collect_launch_receipts legacy_adapter; do
    if "$PY" "$SCRIPTS_DIR/$p.py" --self-test >/tmp/sf_$p.log 2>&1; then
      echo "  [PASS] $p.py --self-test (signature_launch mode)"
    else
      echo "  [FAIL] $p.py --self-test (signature_launch mode)"; sed 's/^/         /' "/tmp/sf_$p.log"; fails=$((fails+1))
    fi
  done
  if "$PY" "$SCRIPTS_DIR/test_launch_route.py" >/tmp/sf_launch_tests.log 2>&1; then
    echo "  [PASS] test_launch_route.py (signature_launch unit tests)"
  else
    echo "  [FAIL] test_launch_route.py"; sed 's/^/         /' /tmp/sf_launch_tests.log; fails=$((fails+1))
  fi
  [ "$fails" -eq 0 ] || die "SELF-TEST" "$fails check(s) failed"
  echo "RESULT: PASS — entry self-test green."
}

write_pin() {
  # Refuses (pin file untouched, exit non-zero) unless --rotation-record is a pin_rotation approval signed
  # with the operator key for this exact tree. CI mints the pin on merge; nothing else may.
  step_deps
  local rec=("$@")
  "$PY" "$FRONT_DOOR" write-pin "${rec[@]+"${rec[@]}"}" || exit 1
}

main() {
  # A6 proof (d): the documented door is USABLE when invoked exactly as documented. Bare
  # invocation is self-describing and exits 0; every real mode below still runs every gate.
  if [ "$#" -eq 0 ]; then
    grep -E '^#( |$)' "$0" | sed 's/^# \{0,1\}//'
    exit 0
  fi
  local mode="" rd="" req_mode="" rotation=""
  while [ $# -gt 0 ]; do
    case "$1" in
      --run-dir) rd="${2:-}"; shift 2 ;;
      --mode) req_mode="${2:-}"; shift 2 ;;
      --self-test) mode="selftest"; shift ;;
      --check-version) mode="checkversion"; shift ;;
      --write-pin) mode="writepin"; shift ;;
      --rotation-record) rotation="${2:-}"; shift 2 ;;
      --scan-only) mode="scanonly"; shift ;;
      --version-only) mode="versiononly"; shift ;;
      -h|--help) grep -E '^#( |$)' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
      *) die "USAGE" "unknown arg: $1" ;;
    esac
  done
  if [ -n "$req_mode" ]; then
    case "$req_mode" in
      signature_launch) run_launch_pipeline "$rd"; return 0 ;;
      legacy_signature_funnel) : ;;  # explicit legacy: fall through unchanged
      *) die "USAGE" "unknown --mode '$req_mode' (signature_launch | legacy_signature_funnel)" ;;
    esac
  fi
  case "$mode" in
    checkversion) step_deps; step_version; echo "VERSION OK" ;;
    selftest) self_test ;;
    writepin) if [ -n "$rotation" ]; then write_pin --rotation-record "$rotation"; else write_pin; fi ;;
    versiononly) step_version; echo "VERSION ok" ;;
    scanonly)
      [ -n "$rd" ] && [ -d "$rd" ] || die "USAGE" "--scan-only needs an existing --run-dir"
      rd="$(cd "$rd" && pwd)"; step_deps; step_bypass_scan "$rd"; echo "BYPASS-SCAN clean: $rd" ;;
    *) run_pipeline "$rd" ;;
  esac
}

main "$@"
