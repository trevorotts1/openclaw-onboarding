#!/usr/bin/env python3
"""bed_mixer: the continuous Suno instrumental music bed under every spoken line.

Owner unit W-E-U8 — manual 02 Part E E8 (Critical) + owner ADDENDUM 2
(2026-10-08: E8 before E10; E7 and E8 share the mixer). stdlib only, zero
paid calls, no transport of its own.

The two failed ads that prove the problem:

  * Leanne's video had digital silence between song slices - only her voice
    while she spoke, no music at all;
  * Kiesett's looped a 1.3 s song scrap at 22% (-13 dB) under each line.

Both came from the same hole the manual names: the docs promise "spoken
lines over the music bed" (SKILL.md decision 30; choice-card-spec
decisions 27/31) but no code built that bed. This module is that code.

What it builds, and never does:

  * ``build_mix(song_master, instrumental, spoken_lines)`` -> mix plan: the
    FULL SONG plays for sung sections; the instrumental plays, UNINTERRUPTED,
    under EVERY spoken line; the switch between song and instrumental is a
    SHORT crossfade on the beat (one beat, from the timing map's beat
    interval / tempo_bpm). Never cut, never loop, never silence the music
    under speech - a proposed timeline that violates that is refused with
    reason codes ``BED_LOOPED`` (Kiesett: a scrap too short to cover the
    span, or the same source window used twice) and ``BED_SILENCE``
    (Leanne: any no-music stretch longer than ``NO_MUSIC_MAX_S`` = 0.3 s).
  * Applies to All Suno AND Velvet Voiceover alike: the spoken-line windows
    are passed in and shaped the same either way (Velvet: the same bed
    under the voiceover, per E7). This module takes no delivery-mode branch.
  * The bed is dipped under speech by ``duck_db`` (default 7.0, validated to
    the documented 6-8 dB; E10's gate fails any line more than 9 dB below
    the sung parts). ponytail: the duck here is a constant gain within each
    spoken line plus the one-beat crossfade ramps at the boundaries; the
    shaped attack/release envelope (short attack/release per E9) is
    W-E-U9's ducking-envelope part of this file - it extends ``gain_points``
    rather than replacing the plan shape.
  * ``render_bed_argv`` renders the plan to one bed wav with ffmpeg: two
    full-length inputs (song, instrumental), per-source time-varying gains
    (piecewise linear, eval=frame), ``amix``. No cut, no aloop, no concat:
    both sources play through aligned to the same wall clock, so the bed
    cannot go silent and cannot repeat.
  * ``attach_mix`` is the ONE seam the final assembler calls: given the
    assembler's timeline (extra keys ``spoken_lines``, ``instrumental_path``,
    optional ``tempo_bpm``/``beat_interval_s``/``duck_db``), it builds the
    plan and hands back (or renders when not dry-running) the single bed
    wav that replaces ``song_path`` for the master render.

The instrumental itself is generated by ``core.audio_c3.extend.suno_extend``
(``plan_instrumental`` / ``generate_instrumental``): a full-length Suno
instrumental of the SAME song (same style text, title, tempo, key) through
Skill 74's submit/wait/save path like every other paid call. This module
carries no generation and no transport; it consumes the resulting record
(duration + audio id).

Run: python3 core/audio_c3/test_bed_mixer_e8.py
"""
from __future__ import annotations

import math

SCHEMA_VERSION = "blackceo.audio-c3/bed-mix/v1"
TOOL_VERSION = "0.1.0"

#: E10 numbers (owner ADDENDUM 2): any stretch with no music longer than
#: this, anywhere in the ad, fails delivery. The mixer itself leaves none.
NO_MUSIC_MAX_S = 0.3

#: E8: the dip under every spoken line, 6-8 dB (E9 refines the envelope).
DEFAULT_DUCK_DB = 7.0
DUCK_MIN_DB = 6.0
DUCK_MAX_DB = 8.0

#: The switch between song and instrumental is short: one beat.
CROSSFADE_MIN_S = 0.2          # sanity floor so a beat of zero never 0-lengths the ramp

SOURCE_SONG = "song"
SOURCE_INSTRUMENTAL = "instrumental"

BED_SOURCES = (SOURCE_SONG, SOURCE_INSTRUMENTAL)


class BedError(ValueError):
    """A proposed mix is not a bed mix. ``code`` names the exact violation."""

    def __init__(self, code, message):
        super().__init__("%s: %s" % (code, message))
        self.code = code


def _num(value, what, code="BAD_NUMBER"):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise BedError(code, "%s: not a number (%r)" % (what, value))
    v = float(value)
    if not math.isfinite(v) or v < 0.0:
        raise BedError(code, "%s: must be finite and >= 0, got %r" % (what, value))
    return v


def _seconds(value, what, code="BAD_DURATION"):
    v = _num(value, what, code)
    if v <= 0.0:
        raise BedError(code, "%s: must be greater than 0, got %r" % (what, value))
    return v


def _beat_interval(song_master, instrumental=None):
    """One beat, from the timing map's beat_interval_s or tempo_bpm."""
    bps = []
    for rec in (song_master, instrumental):
        if isinstance(rec, dict):
            if rec.get("beat_interval_s") is not None:
                bps.append(_seconds(rec.get("beat_interval_s"),
                                    "beat_interval_s", "BED_NO_BEAT"))
            elif rec.get("tempo_bpm") is not None:
                bpm = _num(rec.get("tempo_bpm"), "tempo_bpm", "BED_NO_BEAT")
                if bpm <= 0:
                    raise BedError("BED_NO_BEAT",
                                   "tempo_bpm must be greater than 0 (%r)" % (bpm,))
                bps.append(60.0 / bpm)
    if not bps:
        raise BedError("BED_NO_BEAT",
                       "no beat_interval_s or tempo_bpm on the song master")
    first = bps[0]
    for b in bps[1:]:
        if abs(b - first) > 1e-3:
            raise BedError("BED_NO_BEAT",
                           "beat interval disagrees: %.3f vs %.3f s"
                           % (first, b))
    return first


def _spoken_lines(spoken_lines, duration_s):
    """Normalized, ordered spoken-line windows [(line_id, start, end, text)]."""
    if isinstance(spoken_lines, (str, bytes)) or not hasattr(spoken_lines, "__iter__"):
        raise BedError("SPK_BAD", "spoken_lines: list required")
    out = []
    for i, ln in enumerate(spoken_lines or []):
        if not isinstance(ln, dict):
            raise BedError("SPK_BAD", "spoken_lines[%d]: record required" % i)
        lid = ln.get("line_id") or ln.get("id") or "line-%d" % i
        start = _num(ln.get("start", ln.get("start_s")),
                     "spoken_lines[%d].start" % i, "SPK_BAD")
        end = _num(ln.get("end", ln.get("end_s")),
                   "spoken_lines[%d].end" % i, "SPK_BAD")
        if end <= start:
            raise BedError("SPK_BAD",
                           "spoken_lines[%d] %s: window unordered (%s..%s)"
                           % (i, lid, start, end))
        if start < 0.0 or end > duration_s + 1e-6:
            raise BedError(
                "SPK_RANGE",
                "spoken_lines[%d] %s: window %s..%s outside the bed 0..%s"
                % (i, lid, start, end, duration_s))
        out.append((str(lid), start, end,
                    ln.get("text") if isinstance(ln.get("text"), str) else ""))
    if not out:
        raise BedError("SPK_BAD", "spoken_lines: at least one line required")
    out.sort(key=lambda t: (t[1], t[2]))
    for prev, cur in zip(out, out[1:]):
        if cur[1] < prev[2] - 1e-9:
            raise BedError(
                "SPK_OVERLAP",
                "spoken lines %s and %s overlap (%s vs %s)"
                % (prev[0], cur[0], prev[2], cur[1]))
    return out


def merge_windows(spoken_lines, duration_s):
    """Merge spoken windows (adjacent or touching) -> [(start, end, line_ids)]."""
    norm = _spoken_lines(spoken_lines, duration_s)
    merged = []
    for lid, start, end, _ in norm:
        if merged and start <= merged[-1][1] + 1e-9:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end),
                          merged[-1][2] + [lid])
        else:
            merged.append((start, end, [lid]))
    return merged


def song_windows(duration_s, merged_spoken):
    """The sung spans: everything in 0..duration not under a spoken window."""
    out = []
    cursor = 0.0
    for start, end, _ in merged_spoken:
        if start > cursor + 1e-9:
            out.append((cursor, start))
        cursor = max(cursor, end)
    if duration_s > cursor + 1e-9:
        out.append((cursor, duration_s))
    return out


def check_bed_timeline(bed_segments, duration_s, spoken_windows,
                       source_durations=None, no_music_max_s=NO_MUSIC_MAX_S):
    """Refuse any bed timeline that loops, cuts or silences the music.

    ``bed_segments``: [{"source": "song"|"instrumental", "start_s": a,
    "end_s": b, "source_start_s": s}] - s is where in the source segment
    (a..b) plays. Looped means the same scrap again: a span whose source
    window overruns its source (a wrap would be required: BED_LOOPED), or
    the same source window played twice (BED_LOOPED). Silences means a gap
    between consecutive bed segments longer than ``no_music_max_s`` anywhere
    in 0..duration (BED_SILENCE), or a spoken window not fully covered by
    instrumental segments (BED_SILENCE). Returns the coverage record.
    """
    duration = _seconds(duration_s, "duration_s")
    if source_durations and not isinstance(source_durations, dict):
        raise BedError("BAD_SOURCES", "source_durations: mapping required")
    segs = []
    for i, seg in enumerate(bed_segments or []):
        if not isinstance(seg, dict):
            raise BedError("BAD_BED_SEGMENT", "bed_segments[%d]: record" % i)
        src = seg.get("source")
        if src not in BED_SOURCES:
            raise BedError("BAD_BED_SEGMENT",
                           "bed_segments[%d].source: one of %s, got %r"
                           % (i, list(BED_SOURCES), src))
        a = _num(seg.get("start_s"), "bed_segments[%d].start_s" % i)
        b = _num(seg.get("end_s"), "bed_segments[%d].end_s" % i)
        if b <= a:
            raise BedError("BAD_BED_SEGMENT",
                           "bed_segments[%d]: unordered %s..%s" % (i, a, b))
        if a < 0.0 or b > duration + 1e-6:
            raise BedError("BAD_BED_SEGMENT",
                           "bed_segments[%d]: %s..%s outside 0..%s"
                           % (i, a, b, duration))
        off = _num(seg.get("source_start_s"), "bed_segments[%d].source_start_s" % i)
        if off < 0.0:
            raise BedError("BED_LOOPED",
                           "bed_segments[%d]: negative source offset %s" % (i, off))
        if source_durations:
            dur = _seconds(source_durations.get(src),
                           "source_durations[%s]" % src, "BAD_SOURCES")
            if off + (b - a) > dur + 1e-6:
                raise BedError(
                    "BED_LOOPED",
                    "bed_segments[%d] %s[%s..%s] -> source %s needs %.3f s but "
                    "the source is only %.3f s; wrapping it again would be a "
                    "looped scrap, never a bed" % (i, src, a, b, off, off + b - a, dur))
        segs.append({"source": src, "start_s": a, "end_s": b,
                     "source_start_s": off})

    seen_source_windows = set()
    ordered = sorted(segs, key=lambda s: s["start_s"])
    for prev, cur in zip(ordered, ordered[1:]):
        if prev["source"] == cur["source"] \
                and prev["source_start_s"] == cur["source_start_s"] \
                and abs((prev["end_s"] - prev["start_s"])
                        - (cur["end_s"] - cur["start_s"])) < 1e-9 \
                and prev["start_s"] != cur["start_s"]:
            raise BedError(
                "BED_LOOPED",
                "the same %s source window (%.3f..%.3f of %s, span %.3f) is "
                "played twice at %.3f and %.3f"
                % (prev["source"], prev["source_start_s"],
                   prev["source_start_s"] + prev["end_s"] - prev["start_s"],
                   "the source", prev["end_s"] - prev["start_s"],
                   prev["start_s"], cur["start_s"]))
    for seg in ordered:
        if seg["source"] == SOURCE_INSTRUMENTAL:
            key = (round(seg["source_start_s"], 3),
                   round(seg["end_s"] - seg["start_s"], 3))
            if key in seen_source_windows:
                raise BedError(
                    "BED_LOOPED",
                    "instrumental scrap %r is used as the bed more than once"
                    % (key,))
            seen_source_windows.add(key)

    gaps = []
    if not ordered:
        raise BedError("BED_SILENCE", "no bed segments at all")
    if ordered[0]["start_s"] > no_music_max_s + 1e-6:
        gaps.append((0.0, ordered[0]["start_s"]))
    for prev, cur in zip(ordered, ordered[1:]):
        if cur["start_s"] > prev["end_s"] + no_music_max_s + 1e-6:
            gaps.append((prev["end_s"], cur["start_s"]))
    if ordered[-1]["end_s"] < duration - no_music_max_s - 1e-6:
        gaps.append((ordered[-1]["end_s"], duration))
    if gaps:
        raise BedError(
            "BED_SILENCE",
            "%d no-music stretch(es) over %.3f s: %s"
            % (len(gaps), no_music_max_s,
               "; ".join("%.3f..%.3f" % g for g in gaps[:4])))

    # Every spoken window fully covered by instrumental segments.
    for start, end, lids in merge_windows(spoken_windows, duration):
        instr = [(s["start_s"], s["end_s"]) for s in ordered
                 if s["source"] == SOURCE_INSTRUMENTAL]
        covered = 0.0
        cursor = start
        for a, b in instr:
            seg_start, seg_end = max(a, cursor), min(b, end)
            if seg_end > seg_start:
                covered += seg_end - seg_start
                cursor = seg_end
        span = end - start
        if covered < span - 1e-6:
            raise BedError(
                "BED_SILENCE",
                "spoken %s..%s (%s) has only %.3f s of %.3f under music; a "
                "spoken line plays over the instrumental, uninterrupted"
                % (start, end, ",".join(lids), covered, span))

    return {"duration_s": duration,
            "segments": len(ordered),
            "gaps_over_max": 0,
            "spoken_windows Covered": None,
            "ok": True}


def build_mix(song_master, instrumental, spoken_lines,
              duck_db=DEFAULT_DUCK_DB, beat_interval_s=None, tempo_bpm=None):
    """Mix plan: full song for sung sections, instrumental under EVERY
    spoken line, one-beat crossfades at every switch. Raises BedError
    on any timeline that would cut, loop or silence the music.
    """
    if not isinstance(song_master, dict):
        raise BedError("BAD_SONG_MASTER", "song_master: record required")
    if not isinstance(instrumental, dict):
        raise BedError("BAD_INSTRUMENTAL", "instrumental: record required")
    duration = _seconds(song_master.get("duration_s"),
                        "song_master.duration_s")
    instr_dur = _seconds(instrumental.get("duration_s"),
                         "instrumental.duration_s")
    if instr_dur < duration - 1e-6:
        raise BedError(
            "BED_LOOPED",
            "the instrumental is %.3f s for a %.3f s ad; it would have to be "
            "cut or looped to cover the span, and a bed is never looped - "
            "generate a full-length instrumental first (suno_extend."
            "generate_instrumental)" % (instr_dur, duration))
        # Kiesett's 1.3 s scrap: covered above the moment it is too short.
    song_id = song_master.get("song_id")
    instr_song = instrumental.get("song_id")
    if song_id and instr_song and str(song_id) != str(instr_song):
        raise BedError(
            "BED_SONG_MISMATCH",
            "the instrumental must be of the SAME song: %r vs %r"
            % (song_id, instr_song))
    duck = _num(duck_db, "duck_db", "DIP_RANGE")
    if not DUCK_MIN_DB - 1e-9 <= duck <= DUCK_MAX_DB + 1e-9:
        raise BedError("DIP_RANGE",
                       "duck_db must be %s-%s dB, got %s"
                       % (DUCK_MIN_DB, DUCK_MAX_DB, duck))
    if beat_interval_s is not None:
        song_master = dict(song_master, beat_interval_s=beat_interval_s)
        instrumental = dict(instrumental, beat_interval_s=beat_interval_s)
        instrumental.pop("tempo_bpm", None)
    if tempo_bpm is not None:
        song_master = dict(song_master, tempo_bpm=tempo_bpm)
        instrumental = dict(instrumental, tempo_bpm=tempo_bpm)
    beat = _beat_interval(song_master, instrumental)
    beat = max(CROSSFADE_MIN_S, beat)
    spoken = merge_windows(spoken_lines, duration)
    sung = song_windows(duration, spoken)

    bed, xfade_at = [], []
    cursor = 0.0
    for start, end, lids in spoken:
        if start > cursor + 1e-9:
            # sung span: the FULL SONG at its own timeline position
            bed.append({"source": SOURCE_SONG,
                        "start_s": round(cursor, 6), "end_s": round(start, 6),
                        "source_start_s": round(cursor, 6)})
            cursor = start
        bed.append({"source": SOURCE_INSTRUMENTAL,
                    "start_s": round(start, 6), "end_s": round(end, 6),
                    "source_start_s": round(start, 6)})
        instr_played = end
        cursor = end
    if duration > cursor + 1e-9:
        bed.append({"source": SOURCE_SONG,
                    "start_s": round(cursor, 6), "end_s": round(duration, 6),
                    "source_start_s": round(cursor, 6)})

    # self-proof: the plan cannot loop or silence (raises BedError)
    check_bed_timeline(bed, duration, spoken_lines,
                       source_durations={SOURCE_SONG: duration,
                                         SOURCE_INSTRUMENTAL: instr_dur})

    gain = gain_points(duration, spoken, duck, beat)
    plan = {
        "schema_version": SCHEMA_VERSION,
        "tool": "bed_mixer",
        "tool_version": TOOL_VERSION,
        "duration_s": duration,
        "beat_interval_s": round(beat, 6),
        "duck_db": duck,
        "bed_segments": bed,
        "crossfades": xfade_at,
        "spoken_lines": [
            {"line_id": lid, "start_s": round(start, 6),
             "end_s": round(end, 6), "text": text,
             "bed": SOURCE_INSTRUMENTAL, "bed_present": True}
            for lid, start, end, text in _spoken_lines(spoken_lines, duration)
        ],
        "gain_points": gain,
        "min_bed_gain": round(min(1.0, 10.0 ** (-duck / 20.0)), 6),
        "sources": {"song": {"duration_s": duration,
                             "song_id": song_id or ""},
                    "instrumental": {"duration_s": instr_dur,
                                     "song_id": instr_song or "",
                                     "audio_id": instrumental.get("audio_id")
                                     or ""}},
    }
    return plan


def gain_points(duration_s, merged_spoken, duck_db=DEFAULT_DUCK_DB,
                beat_s=1.0):
    """Piecewise-linear breakpoints [(t, song_gain, instrumental_gain)].

    Song: full gain in sung spans, 0 at the plateau of each spoken span,
    linear through the one-beat crossfade zones at every switch.
    Instrumental: 0 outside the spoken plateau, ``10**(-duck_db/20)`` on it
    (the documented 6-8 dB dip), the same one-beat ramps at the boundaries.
    At every t the two gains sum to at least ``10**(-duck_db/20)`` > 0:
    the bed never reaches digital silence - the Leanne defect is structurally
    impossible in this shape.
    """
    duration = _seconds(duration_s, "duration_s")
    duck = _num(duck_db, "duck_db", "DIP_RANGE")
    if not DUCK_MIN_DB - 1e-9 <= duck <= DUCK_MAX_DB + 1e-9:
        raise BedError("DIP_RANGE",
                       "duck_db must be %s-%s dB, got %s"
                       % (DUCK_MIN_DB, DUCK_MAX_DB, duck))
    bed_gain = 10.0 ** (-duck / 20.0)     # -7 dB ~ 0.4467; never 0
    beat = max(CROSSFADE_MIN_S, _num(beat_s, "beat_s"))
    half = beat / 2.0
    if not merged_spoken:
        spoken = []
    elif isinstance(merged_spoken[0], dict):
        spoken = [(s, e) for s, e, _l in merge_windows(merged_spoken, duration)]
    elif isinstance(merged_spoken[0], (tuple, list)):
        spoken = [(s, e) for _l, s, e, _t in merged_spoken] \
            if len(merged_spoken[0]) == 4 else [
                (s, e) for s, e, _l in merged_spoken]
    else:
        raise BedError("BAD_WINDOWS", "merged_spoken: tuples or records")

    def clamp(v):
        return min(max(v, 0.0), duration)

    song_pts = [(0.0, 1.0)]
    instr_pts = [(0.0, 0.0)]
    for start, end in spoken:
        a0, a1 = clamp(start - half), clamp(start + half)
        b0, b1 = clamp(end - half), clamp(end + half)
        if a1 <= 0.0:                       # spoken begins at 0: no song head
            song_pts[-1] = (0.0, 0.0)
        else:
            song_pts += [(a0, 1.0), (a1, 0.0)]
        song_pts += [(b0, 0.0), (min(b1, duration), 1.0)] \
            if b1 < duration else [(b0, 1.0)]
        if a1 <= 0.0:
            instr_pts[-1] = (0.0, bed_gain)
        else:
            instr_pts += [(a0, 0.0), (a1, bed_gain)]
        if b1 >= duration:
            instr_pts += [(b0, bed_gain), (duration, 0.0)] \
                if b1 > duration else [(b0, 0.0)]
        else:
            instr_pts += [(b0, bed_gain), (b1, 0.0)]
    song_pts += [(duration, song_pts[-1][1])]
    instr_pts += [(duration, instr_pts[-1][1])]

    def compress(pts):
        out = [pts[0]]
        for t, g in pts[1:]:
            if t <= out[-1][0] + 1e-9:
                if abs(g - out[-1][1]) > 1e-9:      # jump: same t, new gain
                    out[-1] = (out[-1][0], g)
            else:
                out.append((round(t, 6), g))
        return out

    s = compress(song_pts)
    i = compress(instr_pts)
    return [(t, _gain_at(s, t), _gain_at(i, t)) for t in sorted(set([p[0] for p in s] + [p[0] for p in i]))]


def _gain_at(points, t):
    """Piecewise-linear value at t."""
    lo = 0
    hi = len(points) - 1
    if t <= points[lo][0]:
        return points[lo][1]
    if t >= points[hi][0]:
        return points[hi][1]
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if points[mid][0] <= t:
            lo = mid
        else:
            hi = mid
    (t0, g0), (t1, g1) = points[lo], points[hi]
    if t1 - t0 < 1e-12:
        return g1
    w = (t - t0) / (t1 - t0)
    return g0 + w * (g1 - g0)


def _expr(points, channel):
    """volume filter expression: piecewise linear gain over t (eval=frame).
    Commas are left for the caller to quote; the value list is monotone."""
    def lerp(pts, t0, t1):
        g0, g1 = _gain_at(pts, t0), _gain_at(pts, t1)
        if t1 - t0 < 1e-9:
            return repr(g1)
        return "({g0}+({g1}-{g0})*min(1\\,max(0\\,(t-{t0})/{dt})))".format(
            g0=repr(round(g0, 6)), g1=repr(round(g1, 6)),
            t0=repr(round(t0, 6)), dt=repr(round(t1 - t0, 6)))
    # nested: evaluate below t1 with the piecewise def; terminal constant at t=+inf
    pts = points
    expr = repr(pts[-1][1])
    for idx in range(len(pts) - 2, -1, -1):
        t1 = pts[idx + 1][0]
        expr = "if(lt(t\\,%s)\\,%s\\,%s)" % (
            repr(round(t1, 6)), lerp(pts, pts[idx][0], t1), expr)
    return expr


def render_bed_argv(plan, song_path, instrumental_path, out_path,
                    ffmpeg="ffmpeg"):
    """ffmpeg argv rendering the mix plan to ONE continuous bed wav.

    Two full-length inputs (0 = song, 1 = instrumental), each shaped by a
    time-varying gain (volume, eval=frame), summed by amix. No aloop, no
    concat, no acrossfade loops: both sources play through once, aligned
    to the same wall clock, so the bed cannot loop and cannot drop out.
    """
    duration = _seconds(plan.get("duration_s"), "plan.duration_s")
    pts = plan.get("gain_points")
    if not pts:
        raise BedError("BAD_PLAN", "plan carries no gain_points")
    song_expr = _expr([(t, s) for t, s, _i in pts], SOURCE_SONG)
    instr_expr = _expr([(t, i) for t, _s, i in pts], SOURCE_INSTRUMENTAL)
    cmd = [ffmpeg, "-y",
           "-i", str(song_path), "-i", str(instrumental_path),
           "-filter_complex",
           "[0:a]volume=volume='%s':eval=frame[a0];"
           "[1:a]volume=volume='%s':eval=frame[a1];"
           "[a0][a1]amix=inputs=2:duration=first:normalize=0[mix];"
           "[mix]atrim=duration=%.6f,apad=whole_dur=%.6f,"
           "aresample=48000[aout]"
           % (song_expr, instr_expr, duration, duration),
           "-map", "[aout]", "-c:a", "pcm_s16le", str(out_path)]
    return cmd


def attach_mix(timeline, base_dir, song_path=None, ffmpeg="ffmpeg",
               runner=None, probe_fn=None, dry_run=False, out_path=None,
               duck_db=DEFAULT_DUCK_DB):
    """The one seam the final assembler calls when spoken lines exist.

    ``timeline`` is the assembler's timeline dict (extra keys: spoken_lines,
    instrumental_path, tempo_bpm / beat_interval_s, optional duck_db).
    Returns a receipt: outcome ok carries the built mix plan, the bed argv
    and the bed wav path; the assembler replaces song_path with the bed wav
    for the master render. dry_run builds and validates everything and
    returns the argv without running it.
    """
    if not isinstance(timeline, dict):
        raise BedError("BAD_TIMELINE", "timeline: record required")
    spoken = timeline.get("spoken_lines")
    instr_path = timeline.get("instrumental_path")
    if not spoken or not instr_path:
        return {"outcome": "noop",
                "reason_code": "NO_SPOKEN_LINES"
                if not spoken else "NO_INSTRUMENTAL",
                "next_action": "no bed mixer step needed",
                "evidence": {"spoken_lines": bool(spoken),
                             "instrumental_path": bool(instr_path)}}
    song_length = timeline.get("song_duration_s")
    instr_length = timeline.get("instrumental_duration_s")
    if (song_length is None or instr_length is None):
        if probe_fn is None:
            return {"outcome": "error",
                    "reason_code": "BED_PROBE_UNAVAILABLE",
                    "next_action": "inject probe_fn (ffprobe duration) or "
                                   "carry song_duration_s / "
                                   "instrumental_duration_s on the timeline",
                    "evidence": {}}
        song_length = probe_fn(song_path if song_path is not None
                               else timeline.get("song_path"))
        instr_length = probe_fn(str(instr_path))
    beat = timeline.get("beat_interval_s")
    bpm = timeline.get("tempo_bpm")
    plan = build_mix(
        {"duration_s": song_length,
         **({"beat_interval_s": beat} if beat is not None else {}),
         **({"tempo_bpm": bpm} if bpm is not None else {}),
         "song_id": timeline.get("song_id") or ""},
        {"duration_s": instr_length,
         "song_id": timeline.get("instrumental_song_id")
         or timeline.get("song_id") or "",
         "audio_id": timeline.get("instrumental_audio_id") or ""},
        spoken, duck_db=timeline.get("duck_db", duck_db))
    argv = render_bed_argv(plan, song_path or timeline.get("song_path"),
                           instr_path,
                           out_path or str(base_dir) + "/bed-mix.wav",
                           ffmpeg=ffmpeg)
    if dry_run:
        return {"outcome": "ok", "reason_code": "DRY_RUN",
                "next_action": "rerun without dry_run to render the bed",
                "evidence": {"plan": plan, "argv": argv}}
    if runner is None:
        import subprocess
        runner = lambda cmd: subprocess.run(cmd, capture_output=True,
                                            text=True, timeout=600,
                                            check=False)
    proc = runner(argv)
    if getattr(proc, "returncode", 1) != 0:
        return {"outcome": "error", "reason_code": "FFMPEG_BED_FAILED",
                "next_action": (getattr(proc, "stderr", "") or "")[-500:],
                "evidence": {"argv": argv,
                             "returncode": getattr(proc, "returncode", 1)}}
    return {"outcome": "ok", "reason_code": "BED_MIXED",
            "next_action": "master render consumes the bed wav as song_path",
            "evidence": {"plan": plan, "argv": argv,
                         "bed_path": out_path or str(base_dir) + "/bed-mix.wav"}}


