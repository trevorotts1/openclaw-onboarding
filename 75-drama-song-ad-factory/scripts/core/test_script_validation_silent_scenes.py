# --- separately invoked old-baseline differential --------------------------
#
# Not a test_ function and never collected by the normal suite. It is evidence
# requested explicitly with S75_BASE_VALIDATOR=<frozen pre-patch path>. It
# states what the OLD validator did next to what the shipped validator now
# does; it is not a skip and the normal suite does not depend on unpatched
# source.

def run_old_baseline_differential(base_path):
    B = _load_module("s75_frozen_baseline", base_path)
    results = []

    def check(name, fn):
        try:
            fn()
        except AssertionError as exc:
            results.append((name, "FAIL: %s" % exc))
        else:
            results.append((name, "PASS"))

    def legitimate_silent():
        base = _verdict(_silent_scene(), module=B)
        assert base["ok"] is False, base["defects"]
        assert "PLACEHOLDER_SCENE" in _codes(base), base["defects"]
        patched = _verdict(_silent_scene(), module=V)
        assert patched["ok"] is True, patched["defects"]

    def valid_speech_baseline():
        base = _verdict(_speech_scene(), module=B)
        assert base["ok"] is True, base["defects"]
        patched = _verdict(_speech_scene(), module=V)
        assert patched["ok"] is True, patched["defects"]

    def one_word_aliases():
        for key, value in (("voiceover_text", "Stop!"),
                           ("dialogue", ["Stop."]),
                           ("narration", "Go."),
                           ("lyrics", ["No."])):
            scene = _silent_scene()
            scene[key] = value
            base = _verdict(scene, module=B)
            patched = _verdict(scene, module=V)
            assert base["ok"] is False, (key, value, "base", base["defects"])
            assert patched["ok"] is False, (key, value, "patched", patched["defects"])
            assert "SILENT_SCENE_LAUNDERED" in _codes(patched), (
                key, value, patched["defects"])

    def malformed_containers():
        for field in _DELIVERY_FIELDS:
            for value in (False, None, "", {}):
                scene = _silent_scene()
                scene[field] = value
                base = _verdict(scene, module=B)
                patched = _verdict(scene, module=V)
                assert base["ok"] is False, (field, value, "base", base["defects"])
                assert patched["ok"] is False, (field, value, "patched", patched["defects"])
                assert "SILENT_SCENE_CONTAINER" in _codes(patched), (
                    field, value, patched["defects"])

    def tuple_containers():
        for field in _DELIVERY_FIELDS:
            scene = _silent_scene()
            scene[field] = ()
            base = _verdict(scene, module=B)
            patched = _verdict(scene, module=V)
            assert base["ok"] is False, (field, "base", base["defects"])
            assert patched["ok"] is False, (field, "patched", patched["defects"])
            assert "SILENT_SCENE_CONTAINER" in _codes(patched), (field, patched["defects"])
            assert field in _defect_fields(patched, "SILENT_SCENE_CONTAINER"), (
                field, patched["defects"])
        scene = _silent_scene()
        scene.update(spoken_dialogue=(), sung_lyrics=(), performance_order=())
        patched = _verdict(scene)
        assert patched["ok"] is False, patched["defects"]
        assert set(_DELIVERY_FIELDS) <= _defect_fields(
            patched, "SILENT_SCENE_CONTAINER"), patched["defects"]

    def empty_list_control():
        scene = _silent_scene()
        for field in _DELIVERY_FIELDS:
            scene[field] = []
        base = _verdict(scene, module=B)
        patched = _verdict(scene, module=V)
        assert base["ok"] is False, base["defects"]
        assert "PLACEHOLDER_SCENE" in _codes(base), base["defects"]
        assert patched["ok"] is True, patched["defects"]

    check("old refuses legitimate silent scene; shipped accepts", legitimate_silent)
    check("valid spoken/sung accepted by old and shipped", valid_speech_baseline)
    check("one-word aliases refused by old and shipped", one_word_aliases)
    check("false/None/''/dict containers refused by old and shipped", malformed_containers)
    check("tuple containers refused with SILENT_SCENE_CONTAINER", tuple_containers)
    check("empty-list silent control: old refuses, shipped accepts", empty_list_control)

    failures = 0
    for name, result in results:
        if result != "PASS":
            failures += 1
        print("%s baseline: %s" % ("PASS" if result == "PASS" else "FAIL", name))
        if result != "PASS":
            print("    %s" % result)
    return failures


if __name__ == "__main__":
    tests = [v for k, v in sorted(globals().items())
             if k.startswith("test_") and callable(v)]
    failures = 0
    for test in tests:
        try:
            test()
        except AssertionError as exc:
            failures += 1
            print("FAIL %s: %s" % (test.__name__, exc))
        else:
            print("ok   %s" % test.__name__)
    print("%d passed, %d failed" % (len(tests) - failures, failures))
    if BASE_PATH:
        print("baseline differential: %s" % BASE_PATH)
        failures += run_old_baseline_differential(BASE_PATH)
    sys.exit(1 if failures else 0)
