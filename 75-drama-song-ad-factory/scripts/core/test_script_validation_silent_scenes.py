def test_one_word_voiceover_or_dialogue_alias_is_performed():
    """One heard word is speech, not metadata."""
    for key, value in (("voiceover_text", "Stop!"),
                       ("dialogue", ["Stop."]),
                       ("narration", "Go."),
                       ("lyrics", ["No."])):
        scene = _silent_scene()
