def _script(scenes):
    return {"schema_version": "s75.script.v1", "artifact_id": "s_w62", "scenes": scenes}


def _verdict(scenes_or_scene, module=V):
    scenes = scenes_or_scene if isinstance(scenes_or_scene, list) else [scenes_or_scene]
    return module.validate_script(_script(scenes), world=WORLD, cast_manifest=CAST)


