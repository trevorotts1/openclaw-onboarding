def _linked_silent_scene():
    """The same silent scene as scene 2, causally linked to spoken scene 1."""
    scene = copy.deepcopy(_silent_scene())
    scene["sequence"] = 2
    scene["causal_predecessor"] = "scene_workshop_001"
    scene["causal_outcome"] = (
        "Because the shortfall stays visible after the notice, the next scene "
        "must plan the first payment.")
