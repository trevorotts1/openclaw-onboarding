        verdict = _verdict(scene)
        assert verdict["ok"] is False, (field, verdict["defects"])
        assert "SILENT_SCENE_CONTAINER" in _codes(verdict), (field, verdict["defects"])
        assert field in _defect_fields(verdict, "SILENT_SCENE_CONTAINER"), (
            field, verdict["defects"])
