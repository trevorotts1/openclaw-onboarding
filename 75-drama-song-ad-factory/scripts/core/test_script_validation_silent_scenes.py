#!/usr/bin/env python3
"""Focused test for the W62 silent-scene repair of script_validation.

One rule under test: a scene that uses the EXISTING explicit staging
declaration ``silent_scene: true`` and performs no words anywhere is a
deliberate action-led silent scene. It is exempt from the dialogue line floor
and from nothing else. Empty dialogue alone authorises nothing; a scene that
still performs words while declaring silence is refused; every other
scene-content check is unchanged.

Two boundaries are explicit. A key that names voiceover or dialogue is speech
on ONE non-empty string ("Stop!" is heard), while a one-word label under an
unrelated metadata key is not classified as speech. And before the exemption
holds the delivery fields a scene writes must be actual LISTS: False, None, an
empty string, a dict or a tuple is a malformed container
(SILENT_SCENE_CONTAINER), never an empty performance. An empty list is the
only empty performance.

The public entry point is the only thing exercised: ``validate_script``. The
validator under test is loaded by a NORMAL IMPORT of the module shipped beside
this file (the installed/post-apply tree); nothing is mocked and no fixture is
generated by the validator itself.

The old-baseline differential is separate evidence. It runs ONLY when an
explicit frozen baseline path is supplied in S75_BASE_VALIDATOR. There is no
default baseline path, so the normal suite passes on an installed/post-apply
tree with the variable unset -- including when the canonical original has
already been patched. Run the differential with:

    S75_BASE_VALIDATOR=<frozen pre-patch script_validation.py> \
        python3 test_script_validation_silent_scenes.py
"""
