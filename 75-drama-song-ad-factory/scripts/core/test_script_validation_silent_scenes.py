# --- refusal cases: silence authorises nothing by itself -------------------

def test_unstated_empty_dialogue_refused():
    scene = _silent_scene()
    scene.pop("silent_scene")
    verdict = _verdict(scene)
    assert verdict["ok"] is False, verdict["defects"]
    assert "PLACEHOLDER_SCENE" in _codes(verdict) or "SCENE_SCHEMA" in _codes(verdict)


def test_malformed_silent_declaration_refused():
    for value in ("true", "True", 1, 0, [], {}, ["true"], 0.0):
        scene = _silent_scene()
        scene["silent_scene"] = value
        verdict = _verdict(scene)
        assert verdict["ok"] is False, value
        assert "SILENT_SCENE_FLAG" in _codes(verdict), (value, verdict["defects"])


def test_contradictory_silence_refused_with_named_codes():
    scene = _silent_scene()
    scene["spoken_dialogue"] = [
        {"line_id": "line_mara_010", "character_id": "char_mara_001",
         "text": "I counted the tray twice and the till is still short."},
        {"line_id": "line_levi_010", "character_id": "char_levi_002",
         "text": "Then say the number out loud before we open."},
    ]
    verdict = _verdict(scene)
    assert verdict["ok"] is False, verdict["defects"]
    assert "SILENT_SCENE_CONTRADICTION" in _codes(verdict), verdict["defects"]
    assert "SILENT_SCENE_LAUNDERED" in _codes(verdict), verdict["defects"]


