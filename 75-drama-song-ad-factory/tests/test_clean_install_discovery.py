def factory_checks(root: Path, tmp: Path):
    skill = root / SKILL_DIR_NAME
    factory = skill / "scripts" / "core" / "intake_preflight" / "factory.py"
    check("factory: skill dir discovered", skill.is_dir(), str(skill))
    entry = factory.is_file()
    check("factory: entrypoint discovered", entry, str(factory))
    if not entry:
        for n in ("factory: intake CLI envelope", "factory: preflight CLI rejects without approval",
                  "factory: 7 core modules import from copy",
                  "factory: contracts + acceptance profile parse"):
            row("FAIL", n, "entrypoint missing")
        return factory

    # intake: empty brief must normalize to waiting/missing-essentials
    rc, env, tail = factory_cli(factory, ["intake", "--brief", "{}",
                                          "--run-id", "w302u7"])
    got = env.get("outcome") if isinstance(env, dict) else None
    ok = (rc == 2 and isinstance(env, dict)
          and got == "waiting"
          and env.get("reason_code") == "missing-essentials"
          and env.get("schema_version") == ENVELOPE)
    check("factory: intake CLI envelope", ok, f"rc={rc} outcome={got} {tail}")

    # preflight without approval must stop fail-closed (names only, no exec)
    rc, env, tail = factory_cli(factory, ["preflight", "--root", str(tmp),
                                          "--run-id", "w302u7"])
    ok = (rc == 4 and isinstance(env, dict)
          and env.get("outcome") == "rejected"
          and env.get("reason_code") == "approval-missing")
    check("factory: preflight CLI rejects without approval",
          ok, f"rc={rc} {tail}")

    # 7 core modules import from the copy under test
    mods = " ".join(CORE_MODULES)
    code = (f"import importlib;mods='{mods}'.split();"
            f"[importlib.import_module(m) for m in mods];"
            f"print('imported:%d' % len(mods))")
    rc, out, err = run([sys.executable, "-c", code],
                       env_extra={"PYTHONPATH": str(skill / "scripts" / "core")})
    check("factory: 7 core modules import from copy",
          rc == 0 and "imported:7" in out, (err or out).strip()[-300:])

    # contracts + acceptance profile parse and carry their version markers
    detail, parsed_ok = [], True
    for rel, marker in (("scripts/core/contracts/campaign-schema.json", "schema_version"),
                        ("scripts/core/contracts/artifact-schema.json", "schema_version"),
                        ("scripts/core/contracts/qc-schema.json", "schema_version"),
                        ("scripts/core/acceptance-profile.json", "profile_version")):
        p = skill / rel
        try:
            text = p.read_text(encoding="utf-8")
            obj = json.loads(text)
            if not isinstance(obj, dict) or marker not in text:
                parsed_ok = False
                detail.append(f"{rel}: missing {marker}")
        except Exception as e:
            parsed_ok = False
            detail.append(f"{rel}: {e}")
    check("factory: contracts + acceptance profile parse", parsed_ok,
          "; ".join(detail))
    return factory


def helper_checks(root: Path, tmp: Path, factory: Path):
    manifest = root / SKILL_DIR_NAME / "DEPENDENCY-MANIFEST.md"
    try:
        text = manifest.read_text(encoding="utf-8")
        absent = [h for h in PROVIDER_HELPERS if h not in text]
        check("helpers: DEPENDENCY-MANIFEST names provider helpers",
              not absent, "missing from manifest: " + ",".join(absent))
    except Exception as e:
        check("helpers: DEPENDENCY-MANIFEST names provider helpers",
              False, str(e))

    for h in REQUIRED_HELPERS:
        sm = root / h / "SKILL.md"
        ok = sm.is_file() and sm.stat().st_size > 0
        check(f"helpers: {h} discovered", ok, str(sm))

    # shipped preflight over the real helpers, approval recorded -> rc 0.
    # A removed helper makes this fail with reference-missing-or-truncated.
    if factory and factory.is_file():
        refs = [root / h / "SKILL.md" for h in REQUIRED_HELPERS]
        rc, env, tail = run_preflight(factory, root, tmp, write_auth(tmp), refs)
        ok = (rc == 0 and isinstance(env, dict)
              and env.get("outcome") == "ok"
              and env.get("reason_code") == "preflight-pass")
        miss = (env or {}).get("data", {}).get("missing") if isinstance(env, dict) else None
        check("helpers: preflight passes with approval (rc 0)", ok,
              f"rc={rc} reason={(env or {}).get('reason_code') if isinstance(env, dict) else None} missing={miss} {tail}")
    else:
        row("FAIL", "helpers: preflight passes with approval (rc 0)",
            "entrypoint missing")


def packaging_checks(root: Path):
    skill = root / SKILL_DIR_NAME
    if not skill.is_dir():
        row("FAIL", "packaging: skill dir present", str(skill))
        return
    missing = [rel for rel in REQUIRED_FILES if not (skill / rel).is_file()]
    check("packaging: required file set present", not missing,
          "missing: " + ",".join(missing))

    # version stamp agreement (SKILL.md frontmatter vs skill-version.txt)
    try:
        sk = (skill / "SKILL.md").read_text(encoding="utf-8")
        fm = sk.split("---")[1] if sk.startswith("---") and sk.count("---") >= 2 else ""
        m = re.search(r"^version:\s*(\S+)", fm, re.M)
        stamp = (skill / "skill-version.txt").read_text(encoding="utf-8").strip()
        check("packaging: SKILL.md version == skill-version.txt",
              bool(m) and m.group(1) == stamp,
              f"frontmatter={m.group(1) if m else None} stamp={stamp}")
    except Exception as e:
        check("packaging: SKILL.md version == skill-version.txt", False, str(e))

    top = {e.name for e in skill.iterdir()}
    unexpected = sorted(top - ALLOWED_TOP)
    check("packaging: top-level allowlist (directive 2.1)", not unexpected,
          "unexpected: " + ",".join(unexpected))

    media, oversize, opaths = [], [], []
    for dirpath, dirnames, filenames in os.walk(skill):
        dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
        for fn in filenames:
            p = Path(dirpath) / fn
            if fn.endswith(".pyc"):
                continue
            try:
                size = p.stat().st_size
            except OSError:
                continue
            if p.suffix.lower() in MEDIA_SUFFIXES:
                media.append(str(p.relative_to(skill)))
            if size > MAX_FILE_BYTES:
                oversize.append(f"{p.relative_to(skill)} ({size}B)")
            if p.suffix.lower() in CODE_SUFFIXES:
                try:
                    if OPERATOR_PATH in p.read_text(encoding="utf-8",
                                                    errors="ignore"):
                        opaths.append(str(p.relative_to(skill)))
                except OSError:
                    pass
    check("packaging: zero media binaries", not media, ",".join(media[:5]))
    check("packaging: zero files over 5MB", not oversize, ",".join(oversize[:5]))
    check("packaging: zero operator paths in code", not opaths,
          ",".join(opaths[:5]))
    polluted = sorted(d for d in POLLUTION_DIRS if (skill / d).exists())
    check("packaging: no repo-pollution dirs at skill root", not polluted,
          ",".join(polluted))


def negative_controls(root: Path, tmp: Path, factory: Path):
    """Hermetic proof that discovery+preflight discriminate on a missing helper."""
    auth = write_auth(tmp)
    # full temp copy: every required helper's SKILL.md present
    full = tmp / "copy-full"
    miss_root = tmp / "copy-missing-helper"
    for root_dir in (full, miss_root):
        root_dir.mkdir(parents=True, exist_ok=True)
        for h in REQUIRED_HELPERS:
            if root_dir is miss_root and h == CONTROL_REMOVED:
                continue
            src = root / h / "SKILL.md"
            if not src.is_file():
                continue          # helper_checks already fails this row
            d = root_dir / h
            d.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, d / "SKILL.md")

    m_full = missing_helpers(full)
    check("control: clean temp copy discovers all helpers", not m_full,
          ",".join(m_full))
    rc, env, tail = run_preflight(factory, full, tmp, auth,
                                  [full / h / "SKILL.md" for h in REQUIRED_HELPERS])
    check("control: preflight passes on clean temp copy",
          rc == 0 and isinstance(env, dict) and env.get("outcome") == "ok",
          f"rc={rc} {tail}")

    m_miss = missing_helpers(miss_root)
    expected = str(miss_root / CONTROL_REMOVED / "SKILL.md")
    check("control: discovery FAILS naming the removed helper",
          m_miss == [expected], f"missing={m_miss}")
    rc, env, tail = run_preflight(
        factory, miss_root, tmp, auth,
        [miss_root / h / "SKILL.md" for h in REQUIRED_HELPERS])
    got = (env or {}).get("data", {}).get("missing") if isinstance(env, dict) else None
    # preflight realpaths its report; compare on the helper path suffix so a
    # symlinked temp dir (/var vs /private/var) cannot flip the control.
    named = (isinstance(got, list) and len(got) == 1
             and str(got[0]).endswith(f"{CONTROL_REMOVED}/SKILL.md"))
    ok = (rc == 1 and isinstance(env, dict)
          and env.get("reason_code") == "reference-missing-or-truncated"
          and named)
    check("control: preflight fails clearly naming the removed helper", ok,
          f"rc={rc} reason={(env or {}).get('reason_code') if isinstance(env, dict) else None} missing={got}")


def main() -> int:
    root, source = resolve_root()
    if root is None:
        print(f"resolve-failure: no clean onboarding root "
              f"(checked env, {SELF.parents[2]}, ~/openclaw-onboarding)",
              file=sys.stderr)
        return 2
    print(f"clean onboarding copy: {root}  (via {source})", flush=True)
    tmp = Path(tempfile.mkdtemp(prefix=f"{BOX}-W3-02-U7-"))
    try:
        factory = factory_checks(root, tmp)
        helper_checks(root, tmp, factory)
        packaging_checks(root)
        if factory and factory.is_file():
            negative_controls(root, tmp, factory)
        else:
            row("FAIL", "control: hermetic helper-removal controls",
                "entrypoint missing")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    npass = sum(1 for s, _, _ in ROWS if s == "ok")
    print(f"SUMMARY: {npass} ok, {len(FAILS)} FAIL, {len(ROWS)} rows")
    if FAILS:
        print("RESULT: FAIL\nfailed rows:\n  - " + "\n  - ".join(FAILS))
        return 1
    print("RESULT: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
