# resolve the clean onboarding copy
def looks_like_onboarding_root(p: Path) -> bool:
    if not p.is_dir():
        return False
    try:
        n = sum(1 for e in p.iterdir()
                if e.is_dir() and re.match(r"^\d{2}-", e.name))
    except OSError:
        return False
    return n >= 5


def resolve_root():
    env = os.environ.get("DSAF_ONBOARDING_ROOT")
    if env:
        return Path(env).expanduser().resolve(), "env:DSAF_ONBOARDING_ROOT"
    local = SELF.parents[2]          # root containing this test when shipped
    if looks_like_onboarding_root(local):
        return local, "checkout:parents[2]"
    home = Path.home() / "openclaw-onboarding"
    if looks_like_onboarding_root(home):
        return home, "clone:~/openclaw-onboarding"
    if (local / SKILL_DIR_NAME).is_dir():
        return local, "fallback:parents[2]-partial"
    if (home / SKILL_DIR_NAME).is_dir():
        return home, "fallback:clone-partial"
    return None, ""


