ROWS = []          # (status, name, detail)
FAILS = []


def row(status, name, detail=""):
    ROWS.append((status, name, detail))
    if status == "FAIL":
        FAILS.append(name)
    line = f"{status}: {name}"
    if detail and status != "ok":
        line += f" ({detail})"
    print(line, flush=True)


def check(name, ok, detail=""):
    row("ok" if ok else "FAIL", name, detail)


