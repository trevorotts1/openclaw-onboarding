# subprocess helpers (never write into the copy under test)
def run(args, env_extra=None):
    env = dict(os.environ)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    if env_extra:
        env.update(env_extra)
    p = subprocess.run(args, capture_output=True, text=True, env=env)
    return p.returncode, p.stdout, p.stderr


def factory_cli(factory: Path, args):
    rc, out, err = run([sys.executable, str(factory)] + args)
    try:
        env = json.loads(out)
    except Exception:
        env = None
    return rc, env, (err or out).strip()[-400:]


def write_auth(tmp: Path) -> Path:
    auth = tmp / "auth.json"
    auth.write_text(json.dumps(
        {"scope": "campaign", "expires_unix": int(time.time()) + 3600}))
    return auth


def run_preflight(factory: Path, root: Path, storage: Path, auth: Path,
                  refs):
    args = ["preflight", "--root", str(root), "--storage-dir", str(storage),
            "--auth-file", str(auth), "--run-id", "w302u7"]
    for r in refs:
        args += ["--ref", str(r)]
    return factory_cli(factory, args)


def missing_helpers(root: Path):
    """Return SKILL.md paths under root that a clean copy must carry but does not."""
    out = []
    for h in REQUIRED_HELPERS:
        sm = root / h / "SKILL.md"
        if not (sm.is_file() and sm.stat().st_size > 0):
            out.append(str(sm))
    return out


