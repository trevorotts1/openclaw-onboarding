#!/usr/bin/env python3
"""W3-02-U7 — clean-install discovery test (directive 2.1, 2.4, 30).

Discovers, against a CLEAN ONBOARDING COPY:

  factory  — entrypoint present; intake + preflight CLIs run and emit the
             pinned envelope (schema_version, outcome/exit-code agreement);
             the 7 core modules import from the copy; contracts and the
             acceptance profile parse.
  helpers  — the nine onboarding helper skills named by DEPENDENCY-MANIFEST.md
             section 2 (provider skills 66/67/68/74 per directive 2.4, plus
             install-path skills 07/46/30/25/27) each exist with a non-empty
             SKILL.md; the shipped preflight passes over them with approval
             recorded (rc 0, preflight-pass).
  packaging— directive-2.1 top-level allowlist, required file set, version
             stamp agreement (SKILL.md frontmatter vs skill-version.txt),
             zero media binaries, zero files >5 MB, zero operator paths in
             code (.py/.sh/.js/.json — .md evidence docs are exempt: they
             cite scan paths by design), no repo-pollution dirs at skill root.
             Runtime caches (__pycache__/*.pyc) are excluded: they are
             generated by running this test, not shipped.

Acceptance (fails when a helper skill is removed) is proved twice:

  1. in place — a helper removed from the resolved clean copy makes both
     helper discovery and preflight fail, naming the helper (exit 1);
  2. hermetic negative controls — this test always builds its own temp copy
     of all nine helper SKILL.md files, proves discovery + preflight PASS on
     it, then repeats with ONE helper removed and proves discovery + preflight
     FAIL naming it. A control that does not discriminate fails the test.

Clean-copy resolution, first match wins:
  DSAF_ONBOARDING_ROOT=<path>   explicit copy (always wins)
  parents[2] of this file       the checkout this test ships in, when it
                                looks like an onboarding root (>=5 numbered
                                NN-* skill dirs)
  ~/openclaw-onboarding         the operator's clean clone
A staging tree that is not a full onboarding root is never treated as the
clean copy. No root found at all = exit 2 (tooling), never a silent pass.

stdlib only, no network, no provider calls, no repo writes (subprocesses run
with PYTHONDONTWRITEBYTECODE=1). Exit 0 = every row pass, 1 = any row FAIL,
2 = resolve failure (nothing checked). Never writes a verdict file.
"""
