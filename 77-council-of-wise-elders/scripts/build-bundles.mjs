#!/usr/bin/env node
// Council of Wise Elders: bundle builder (CWE-039 final packaging).
// Computes the deterministic tree hash of this skill folder (sorted
// relative paths, per-file SHA-256, aggregate over "sha256  path"
// lines), writes the generated manifest.json, and generates the
// distributable council-of-wise-elders.skill archive.
//
// The manifest excludes itself, any .skill archive, and generated runtime/dist and runtime/node_modules trees. The archive is
// a deterministic zip (entries sorted, fixed 1980-01-01 timestamps)
// holding the tree under the council-of-wise-elders/ root directory,
// as the directive's package layout requires.
//
// The archived copy of the Russell Brunson pack is the distribution
// copy required by CWE-012 acceptance condition 3: the private_scope
// items never enter a distributable artifact. Packaging therefore
// applies the verified two-part strip to a staging copy (the source
// tree itself is never modified):
//   (1) drop every item whose scope is private_scope;
//   (2) scrub, sentence by sentence, prose references to the stripped
//       item IDs or to the private evidence ID prefix from the
//       remaining pack JSON string fields, and drop the file-level
//       note sentences that describe the removed private_scope items.
// The Brunson profile's distribution block and source-basis status
// are then set to describe the stripped copy truthfully. The builder
// self-checks the staging tree: zero residual references to the
// stripped IDs or the private evidence prefix, or it fails and no
// archive is produced. The staged copy carries its own manifest.json
// computed over the stripped tree, so doctor passes on an extracted
// archive. Only the outer source manifest records the archive SHA-256.
// The inner manifest describes an extracted distribution without requiring
// a self-nested archive or a circular archive checksum.
// Usage: node build-bundles.mjs [--root <skill-folder>]

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { deflateRawSync } from "node:zlib";
import {
  cpSync, existsSync, mkdtempSync, readFileSync, readdirSync,
  renameSync, rmSync, statSync, writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const rootIdx = args.indexOf("--root");
const root = rootIdx >= 0
  ? resolve(args[rootIdx + 1])
  : resolve(dirname(fileURLToPath(import.meta.url)), "..");

const ARCHIVE_FILE = "council-of-wise-elders.skill";
const ARCHIVE_TMP = ".council-of-wise-elders.skill.tmp";
const ARCHIVE_ROOT = "council-of-wise-elders";
const BRUNSON_DIR = "advisors/russell-brunson";
const ITEM_FILES = [
  `${BRUNSON_DIR}/frameworks.json`,
  `${BRUNSON_DIR}/failure-patterns.json`,
];
// The strip targets are derived from the pack data at run time (the
// private_scope item IDs from the pack item files; the private
// evidence prefix from the user_private source record in
// sources.json), never hardcoded here: this script ships inside the
// archive, and the finished artifact must contain no residual
// reference to what was stripped.
const DISTRIBUTION_NOTE =
  "Private-scope material recorded for this seat is excluded from this distributable copy at packaging " +
  "(CWE-012 acceptance condition 3): the copy carries no private-scope items, no private evidence " +
  "references, and no private source text. The seat's shared works are unaffected.";

function fail(message) {
  console.log(`FAIL ${message}`);
  process.exit(1);
}

function isGeneratedRuntimePath(rel) {
  return rel === "runtime/dist" || rel.startsWith("runtime/dist/")
    || rel === "runtime/node_modules" || rel.startsWith("runtime/node_modules/");
}

function walk(dir, out = [], base = dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    const rel = relative(base, p).split("\\").join("/");
    if (isGeneratedRuntimePath(rel)) continue;
    if (statSync(p).isDirectory()) walk(p, out, base);
    else out.push(p);
  }
  return out;
}

const HASH_METHOD = "SHA-256 per file over sorted relative paths; aggregate is SHA-256 of the lines \"<sha256>  <path>\" joined by newlines with a trailing newline. manifest.json, any .skill archive, runtime/dist and runtime/node_modules are excluded.";
const ARCHIVE_BLOCK = {
  file: ARCHIVE_FILE,
  note: "Generated by scripts/build-bundles.mjs at final packaging (CWE-039). The archive holds the distribution copy of this tree under the council-of-wise-elders/ root; its Brunson pack copy has the private_scope items removed and prose references to them scrubbed (CWE-012 acceptance condition 3). Only the outer source manifest records the archive SHA-256; the extracted distribution does not contain a nested archive.",
};

function computeManifest(dir, sourceCommit, version, archive) {
  const files = [];
  for (const p of walk(dir)) {
    const rel = relative(dir, p).split("\\").join("/");
    if (rel === "manifest.json" || rel.endsWith(".skill")) continue;
    const bytes = readFileSync(p);
    files.push({
      path: rel,
      sha256: createHash("sha256").update(bytes).digest("hex"),
      bytes: bytes.length,
    });
  }
  files.sort((a, b) => (a.path < b.path ? -1 : 1));
  const aggregate = createHash("sha256")
    .update(files.map((f) => `${f.sha256}  ${f.path}`).join("\n") + "\n")
    .digest("hex");
  return {
    skill: "council-of-wise-elders",
    skill_version: version,
    generated_by: "scripts/build-bundles.mjs",
    source_commit: sourceCommit,
    file_count: files.length,
    aggregate_sha256: aggregate,
    hash_method: HASH_METHOD,
    archive,
    files,
  };
}

// --- deterministic zip writer (stored metadata, deflate payload) ---
const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  return table;
})();

function crc32(buf) {
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) {
    crc = CRC_TABLE[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function buildZip(entries) {
  // entries: [{ name, data }] already sorted by name.
  const chunks = [];
  const central = [];
  let offset = 0;
  const DOS_DATE_1980_01_01 = (0 << 9) | (1 << 5) | 1;
  for (const entry of entries) {
    const nameBuf = Buffer.from(entry.name, "utf8");
    const compressed = deflateRawSync(entry.data, { level: 9 });
    const crc = crc32(entry.data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);            // version needed
    local.writeUInt16LE(0x0800, 6);        // UTF-8 filename flag
    local.writeUInt16LE(8, 8);             // deflate
    local.writeUInt16LE(0, 10);            // mod time: 00:00:00
    local.writeUInt16LE(DOS_DATE_1980_01_01, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(entry.data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);            // no extra field
    chunks.push(local, nameBuf, compressed);

    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0);
    cen.writeUInt16LE(20, 4);              // version made by
    cen.writeUInt16LE(20, 6);              // version needed
    cen.writeUInt16LE(0x0800, 8);
    cen.writeUInt16LE(8, 10);
    cen.writeUInt16LE(0, 12);
    cen.writeUInt16LE(DOS_DATE_1980_01_01, 14);
    cen.writeUInt32LE(crc, 16);
    cen.writeUInt32LE(compressed.length, 20);
    cen.writeUInt32LE(entry.data.length, 24);
    cen.writeUInt16LE(nameBuf.length, 28);
    cen.writeUInt32LE((0o100644 << 16) >>> 0, 38); // regular file, 0644
    cen.writeUInt32LE(offset, 42);
    central.push(Buffer.concat([cen, nameBuf]));
    offset += local.length + nameBuf.length + compressed.length;
  }
  const centralBuf = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...chunks, centralBuf, end]);
}

// --- the Brunson distribution strip (staging copy only) ---
function stripBrunsonPack(staging) {
  const packDir = join(staging, BRUNSON_DIR);

  // Derive the strip list from the source data, and require it to be
  // exactly the three items recorded at CWE-012 / CWE-039.
  const stripIds = [];
  for (const rel of ITEM_FILES) {
    const data = JSON.parse(readFileSync(join(staging, rel), "utf8"));
    for (const item of data.items ?? []) {
      if (item.scope === "private_scope") stripIds.push(item.id);
    }
  }
  stripIds.sort();
  if (stripIds.length !== 3) {
    fail(`strip derivation drift: found ${stripIds.length} private_scope items (${stripIds.join(", ")}), expected exactly 3 per the CWE-012 record`);
  }
  const sources = JSON.parse(readFileSync(join(packDir, "sources.json"), "utf8"));
  const privateRecord = (sources.records ?? []).find((r) => r.allowed_scope === "user_private");
  if (!privateRecord?.export_source_id) {
    fail("strip derivation: no user_private source record found in the Brunson pack sources.json");
  }
  const privatePrefix = `ev-${privateRecord.export_source_id.replace(/^src-/, "")}-`;
  const tokens = [...stripIds, privatePrefix];
  const touched = [];

  function scrubString(value, path, file, extraTokens) {
    const all = extraTokens ? [...tokens, ...extraTokens] : tokens;
    if (!all.some((t) => value.includes(t))) return value;
    const kept = value
      .split(/(?<=[.!?])\s+/)
      .filter((s) => !all.some((t) => s.includes(t)));
    touched.push(`${file}:${path}`);
    return kept.join(" ").trim();
  }
  function scrubValue(value, path, file, isItemFile) {
    if (typeof value === "string") {
      const extra = isItemFile && path === "$.note" ? ["private_scope"] : null;
      return scrubString(value, path, file, extra);
    }
    if (Array.isArray(value)) {
      const out = [];
      value.forEach((el, i) => {
        const r = scrubValue(el, `${path}[${i}]`, file, isItemFile);
        if (r !== "") out.push(r);
      });
      return out;
    }
    if (value && typeof value === "object") {
      const out = {};
      for (const [k, v] of Object.entries(value)) {
        const r = scrubValue(v, `${path}.${k}`, file, isItemFile);
        if (r !== "") out[k] = r;
      }
      return out;
    }
    return value;
  }

  for (const name of readdirSync(packDir).sort()) {
    if (!name.endsWith(".json")) continue;
    const rel = `${BRUNSON_DIR}/${name}`;
    const p = join(staging, rel);
    const before = readFileSync(p, "utf8");
    const canonical = JSON.stringify(JSON.parse(before));
    let data = JSON.parse(before);
    if (ITEM_FILES.includes(rel)) {
      const kept = (data.items ?? []).filter((i) => i.scope !== "private_scope");
      if (kept.length !== data.items.length) {
        touched.push(`${name}:$.items (dropped ${(data.items.length - kept.length)} private_scope)`);
      }
      data.items = kept;
    }
    data = scrubValue(data, "$", name, ITEM_FILES.includes(rel));
    if (rel === `${BRUNSON_DIR}/profile.json`) {
      data.distribution = {
        ...data.distribution,
        contains_private_scope_material: false,
        distribution_ready: true,
        note: DISTRIBUTION_NOTE,
      };
      data.source_basis = (data.source_basis ?? []).map((entry) =>
        entry.status === "present_private_scope"
          ? { ...entry, status: "excluded_from_distribution_private_scope" }
          : entry);
      touched.push("profile.json:$.distribution (packaging record)");
    }
    // Write back only when the strip changed the VALUE; a formatting
    // difference alone must not rewrite a pack file's bytes.
    const after = JSON.stringify(data);
    if (after !== canonical) writeFileSync(p, after);
  }

  // Self-check: no residual reference anywhere in the staging tree.
  for (const p of walk(staging)) {
    const text = readFileSync(p, "utf8");
    for (const t of tokens) {
      if (text.includes(t)) {
        fail(`strip self-check: residual reference ${t} in ${relative(staging, p)}`);
      }
    }
  }
  return { stripIds, touched };
}

// --- main ---
let sourceCommit = null;
try {
  sourceCommit = execFileSync("git", ["-C", root, "rev-parse", "HEAD"],
    { encoding: "utf8" }).trim();
} catch { /* not a git checkout: source commit stays null */ }
const version = existsSync(join(root, "version"))
  ? readFileSync(join(root, "version"), "utf8").trim() : null;

const stageParent = mkdtempSync(join(process.env.TMPDIR || tmpdir(), "cwe039-bundles-"));
const staging = join(stageParent, "tree");
const tmpZipPath = join(root, ARCHIVE_TMP);
try {
  cpSync(root, staging, {
    recursive: true,
    filter: (src) => {
      const rel = relative(root, src).split("\\").join("/");
      return rel !== "manifest.json" && !rel.endsWith(".skill")
        && rel !== ARCHIVE_TMP && !isGeneratedRuntimePath(rel);
    },
  });

  const { stripIds, touched } = stripBrunsonPack(staging);
  console.log(`strip: removed items ${stripIds.join(", ")} from the distribution copy`);
  console.log(`strip: scrubbed or edited fields: ${touched.join("; ")}`);

  const innerManifest = computeManifest(staging, sourceCommit, version, {
    ...ARCHIVE_BLOCK, status: "extracted_distribution",
  });
  writeFileSync(join(staging, "manifest.json"), JSON.stringify(innerManifest, null, 2) + "\n");

  const entries = walk(staging)
    .map((p) => ({
      name: `${ARCHIVE_ROOT}/${relative(staging, p).split("\\").join("/")}`,
      data: readFileSync(p),
    }))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
  const zip = buildZip(entries);
  writeFileSync(tmpZipPath, zip);
  renameSync(tmpZipPath, join(root, ARCHIVE_FILE));
  const archiveSha = createHash("sha256").update(zip).digest("hex");
  console.log(`archive ${ARCHIVE_FILE}: ${zip.length} bytes, sha256 ${archiveSha}, ${entries.length} entries under ${ARCHIVE_ROOT}/`);

  const manifest = computeManifest(root, sourceCommit, version, {
    ...ARCHIVE_BLOCK, status: "generated", sha256: archiveSha,
  });
  writeFileSync(join(root, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(`manifest.json written: ${manifest.file_count} files, aggregate ${manifest.aggregate_sha256}`);
} finally {
  rmSync(stageParent, { recursive: true, force: true });
  if (existsSync(tmpZipPath)) rmSync(tmpZipPath, { force: true });
}
